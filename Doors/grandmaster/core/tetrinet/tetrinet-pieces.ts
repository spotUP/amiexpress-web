export function getTetriNetShape(type: PieceType, rotation: number): number[][] {
  const rotations = SHAPES[type];
  const index = rotation % rotations.length;
  return rotations[index];
}

export function getRotationCount(type: PieceType): number {
  return SHAPES[type].length;
}
