#!/usr/bin/env node
/**
 * Generate LVO name maps, parameter metadata, and struct field lookups
 * from the NDK structs index (mcp-server/data/ndk-structs-index.json).
 *
 * Output files:
 *   web/backend/src/amiga-emulation/constants/lvo-names.generated.ts
 *   web/backend/src/amiga-emulation/constants/lvo-params.generated.ts
 *   web/backend/src/amiga-emulation/constants/struct-fields.generated.ts
 *
 * Usage:
 *   node dev/scripts/generate-lvo-maps.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const INDEX_PATH = path.join(ROOT, 'mcp-server/data/ndk-structs-index.json');
const OUT_DIR = path.join(ROOT, 'web/backend/src/amiga-emulation/constants');

// Structs we actively use in the emulator (anchored lookups only)
const KEY_STRUCTS = [
  'process', 'task', 'commandlineinterface', 'msgport', 'message',
  'filehandle', 'filelock', 'node', 'library', 'device',
  'iorequest', 'iostdreq', 'ioexttd', 'execbase', 'dosbase',
  'dospacket', 'fileinfoblock', 'datestamp', 'rootnode', 'dosinfo',
  'devicenode', 'devproc', 'segment', 'resident', 'memheader',
  'memchunk', 'mementry', 'signalsemaphore', 'semaphore',
  'semaphorerequest', 'interrupt', 'intrvector', 'softintlist',
  'list', 'minlist', 'minnode',
];

function loadIndex() {
  if (!fs.existsSync(INDEX_PATH)) {
    console.error(`Index not found: ${INDEX_PATH}`);
    console.error('Run: node mcp-server/build-indexes.js');
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(INDEX_PATH, 'utf8'));
}

function generateLvoNames(index) {
  const lines = [
    '// AUTO-GENERATED by dev/scripts/generate-lvo-maps.js',
    '// Source: mcp-server/data/ndk-structs-index.json (NDK 3.1)',
    '// Do not edit manually -- regenerate with: node dev/scripts/generate-lvo-maps.js',
    '',
    '/**',
    ' * Complete LVO name maps for all AmigaOS libraries.',
    ' * Maps negative byte offset -> function name.',
    ' * Used by LibraryTraps for stub naming and debug logging.',
    ' */',
    '',
  ];

  const libs = index.libraries || {};
  const libNames = Object.keys(libs).sort();
  let totalFunctions = 0;

  // Generate a constant name from library name: "dos.library" -> "DOS_LVO_NAMES"
  function constName(libName) {
    return libName
      .replace(/\.library$/, '')
      .replace(/\.device$/, '_DEV')
      .replace(/\.resource$/, '_RES')
      .replace(/[^a-zA-Z0-9]/g, '_')
      .toUpperCase() + '_LVO_NAMES';
  }

  // Build the ALL_LVO_NAMES map and individual maps
  const allMaps = [];

  for (const libName of libNames) {
    const lib = libs[libName];
    const fns = lib.functions || {};
    const fnNames = Object.keys(fns);
    if (fnNames.length === 0) continue;

    const cName = constName(libName);
    const entries = [];

    for (const fnName of fnNames) {
      const fn = fns[fnName];
      if (fn.lvo != null) {
        entries.push({ offset: fn.lvo, name: fn.name || fnName });
        totalFunctions++;
      }
    }

    if (entries.length === 0) continue;

    entries.sort((a, b) => b.offset - a.offset); // -30, -36, -42, ...

    lines.push(`export const ${cName}: Record<number, string> = {`);
    for (const e of entries) {
      lines.push(`  [${e.offset}]: '${e.name}',`);
    }
    lines.push('};');
    lines.push('');

    allMaps.push({ libName, cName });
  }

  // Master lookup: library name -> LVO name map
  lines.push('/** Master lookup: library name (lowercase) -> LVO name map */');
  lines.push('export const ALL_LVO_NAMES: Record<string, Record<number, string>> = {');
  for (const { libName, cName } of allMaps) {
    lines.push(`  '${libName.toLowerCase()}': ${cName},`);
  }
  lines.push('};');
  lines.push('');

  // Helper function
  lines.push('/**');
  lines.push(' * Look up a function name by library and LVO offset.');
  lines.push(' * Returns the function name or undefined if not found.');
  lines.push(' */');
  lines.push('export function getLvoName(library: string, offset: number): string | undefined {');
  lines.push("  const map = ALL_LVO_NAMES[library.toLowerCase()];");
  lines.push('  return map ? map[offset] : undefined;');
  lines.push('}');
  lines.push('');

  console.log(`  LVO names: ${totalFunctions} functions across ${allMaps.length} libraries`);
  return lines.join('\n');
}

function generateLvoParams(index) {
  const lines = [
    '// AUTO-GENERATED by dev/scripts/generate-lvo-maps.js',
    '// Source: mcp-server/data/ndk-structs-index.json (NDK 3.1)',
    '// Do not edit manually -- regenerate with: node dev/scripts/generate-lvo-maps.js',
    '',
    '/**',
    ' * LVO parameter metadata for debug logging.',
    ' * Maps negative byte offset -> array of { name, reg, type }.',
    ' * Only includes functions that have documented register assignments.',
    ' */',
    '',
    'export interface LvoParam {',
    '  name: string;',
    '  reg: string;',
    '  type: string;',
    '}',
    '',
  ];

  const libs = index.libraries || {};
  const libNames = Object.keys(libs).sort();
  let totalAnnotated = 0;

  function constName(libName) {
    return libName
      .replace(/\.library$/, '')
      .replace(/\.device$/, '_DEV')
      .replace(/\.resource$/, '_RES')
      .replace(/[^a-zA-Z0-9]/g, '_')
      .toUpperCase() + '_LVO_PARAMS';
  }

  const allMaps = [];

  for (const libName of libNames) {
    const lib = libs[libName];
    const fns = lib.functions || {};
    const fnNames = Object.keys(fns);
    if (fnNames.length === 0) continue;

    const cName = constName(libName);
    const entries = [];

    for (const fnName of fnNames) {
      const fn = fns[fnName];
      if (fn.lvo == null || !fn.inputs || fn.inputs.length === 0) continue;

      const params = fn.inputs.map(inp => ({
        name: inp.name || 'unknown',
        reg: (inp.regs && inp.regs[0]) || '?',
        type: inp.type || 'ULONG',
      }));

      entries.push({ offset: fn.lvo, params });
      totalAnnotated++;
    }

    if (entries.length === 0) continue;

    entries.sort((a, b) => b.offset - a.offset);

    lines.push(`export const ${cName}: Record<number, LvoParam[]> = {`);
    for (const e of entries) {
      const paramStr = e.params.map(p =>
        `{ name: '${p.name}', reg: '${p.reg}', type: '${p.type}' }`
      ).join(', ');
      lines.push(`  [${e.offset}]: [${paramStr}],`);
    }
    lines.push('};');
    lines.push('');

    allMaps.push({ libName, cName });
  }

  // Master lookup
  lines.push('/** Master lookup: library name (lowercase) -> LVO param map */');
  lines.push('export const ALL_LVO_PARAMS: Record<string, Record<number, LvoParam[]>> = {');
  for (const { libName, cName } of allMaps) {
    lines.push(`  '${libName.toLowerCase()}': ${cName},`);
  }
  lines.push('};');
  lines.push('');

  // Helper
  lines.push('/**');
  lines.push(' * Look up parameter metadata by library and LVO offset.');
  lines.push(' */');
  lines.push('export function getLvoParams(library: string, offset: number): LvoParam[] | undefined {');
  lines.push("  const map = ALL_LVO_PARAMS[library.toLowerCase()];");
  lines.push('  return map ? map[offset] : undefined;');
  lines.push('}');
  lines.push('');

  console.log(`  LVO params: ${totalAnnotated} annotated functions`);
  return lines.join('\n');
}

function generateStructFields(index) {
  const lines = [
    '// AUTO-GENERATED by dev/scripts/generate-lvo-maps.js',
    '// Source: mcp-server/data/ndk-structs-index.json (NDK 3.1)',
    '// Do not edit manually -- regenerate with: node dev/scripts/generate-lvo-maps.js',
    '',
    '/**',
    ' * Struct field layouts for key AmigaOS data structures.',
    ' * Used for annotating memory accesses in 68K debug logging.',
    ' * Only includes structs actively used in the emulator.',
    ' */',
    '',
    'export interface StructField {',
    '  name: string;',
    '  offset: number;',
    '  size: number;',
    '  type: string;',
    '}',
    '',
  ];

  const structs = index.structs || {};
  let totalFields = 0;
  const generated = [];

  for (const key of KEY_STRUCTS) {
    const s = structs[key];
    if (!s) continue;

    const fields = (s.fields || []).filter(f => f.size > 0); // skip LABELs
    if (fields.length === 0) continue;

    const cName = s.name.toUpperCase() + '_FIELDS';
    lines.push(`export const ${cName}: StructField[] = [`);
    for (const f of fields) {
      lines.push(`  { name: '${f.name}', offset: ${f.offset}, size: ${f.size}, type: '${f.type}' },`);
      totalFields++;
    }
    lines.push('];');
    lines.push('');

    generated.push({ structName: s.name, key, cName });
  }

  // Master lookup
  lines.push('/** Struct name (case-insensitive) -> field layout */');
  lines.push('export const STRUCT_FIELDS: Record<string, StructField[]> = {');
  for (const { structName, key, cName } of generated) {
    lines.push(`  '${key}': ${cName},`);
    // Also add by display name for convenience
    if (key !== structName.toLowerCase()) {
      lines.push(`  '${structName.toLowerCase()}': ${cName},`);
    }
  }
  lines.push('};');
  lines.push('');

  // Field-by-offset lookup helper
  lines.push('/**');
  lines.push(' * Look up what field is at a given offset within a struct.');
  lines.push(' * Returns the field that contains the offset, or undefined.');
  lines.push(' */');
  lines.push('export function getFieldAtOffset(structName: string, offset: number): StructField | undefined {');
  lines.push("  const fields = STRUCT_FIELDS[structName.toLowerCase()];");
  lines.push('  if (!fields) return undefined;');
  lines.push('  // Find the field whose range [offset, offset+size) contains the target');
  lines.push('  for (const f of fields) {');
  lines.push('    if (offset >= f.offset && offset < f.offset + f.size) return f;');
  lines.push('  }');
  lines.push('  return undefined;');
  lines.push('}');
  lines.push('');

  console.log(`  Struct fields: ${totalFields} fields across ${generated.length} structs`);
  return lines.join('\n');
}

// Main
console.log('Loading NDK index...');
const index = loadIndex();

console.log('Generating LVO name maps...');
const lvoNames = generateLvoNames(index);
const lvoNamesPath = path.join(OUT_DIR, 'lvo-names.generated.ts');
fs.writeFileSync(lvoNamesPath, lvoNames);
console.log(`  -> ${lvoNamesPath}`);

console.log('Generating LVO param metadata...');
const lvoParams = generateLvoParams(index);
const lvoParamsPath = path.join(OUT_DIR, 'lvo-params.generated.ts');
fs.writeFileSync(lvoParamsPath, lvoParams);
console.log(`  -> ${lvoParamsPath}`);

console.log('Generating struct field lookups...');
const structFields = generateStructFields(index);
const structFieldsPath = path.join(OUT_DIR, 'struct-fields.generated.ts');
fs.writeFileSync(structFieldsPath, structFields);
console.log(`  -> ${structFieldsPath}`);

console.log('Done.');
